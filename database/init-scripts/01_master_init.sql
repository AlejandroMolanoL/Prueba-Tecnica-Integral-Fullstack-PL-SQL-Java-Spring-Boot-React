    FUNCTION FN_REPORTE_COMERCIANTES_ACTIVOS RETURN SYS_REFCURSOR IS
        v_cursor SYS_REFCURSOR;
    BEGIN
        OPEN v_cursor FOR
            SELECT c.ID_COMERCIANTE, c.NOMBRE_RAZON_SOCIAL, c.DEPARTAMENTO, c.MUNICIPIO, c.TELEFONO, c.CORREO_ELECTRONICO,
                   c.FECHA_REGISTRO, c.ESTADO, COUNT(e.ID_ESTABLECIMIENTO) AS CANTIDAD_ESTABLECIMIENTOS,
                   NVL(SUM(e.INGRESOS), 0) AS TOTAL_ACTIVOS, NVL(SUM(e.NUMERO_EMPLEADOS), 0) AS CANTIDAD_EMPLEADOS
            FROM COMERCIANTE c LEFT JOIN ESTABLECIMIENTO e ON c.ID_COMERCIANTE = e.ID_COMERCIANTE
            WHERE c.ESTADO IN ('Registrado', 'Activo')
            GROUP BY c.ID_COMERCIANTE, c.NOMBRE_RAZON_SOCIAL, c.DEPARTAMENTO, c.MUNICIPIO, c.TELEFONO, c.CORREO_ELECTRONICO, c.FECHA_REGISTRO, c.ESTADO
            ORDER BY COUNT(e.ID_ESTABLECIMIENTO) DESC, c.NOMBRE_RAZON_SOCIAL ASC;
        RETURN v_cursor;
    END FN_REPORTE_COMERCIANTES_ACTIVOS;
