    BEGIN
        IF P_CORREO IS NULL OR TRIM(P_CORREO) IS NULL THEN RETURN TRUE; END IF;
        IF REGEXP_LIKE(TRIM(P_CORREO), '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$') THEN RETURN TRUE; ELSE RETURN FALSE; END IF;
    END FN_VALIDAR_CORREO;

    FUNCTION FN_VALIDAR_TELEFONO(P_TELEFONO IN VARCHAR2) RETURN BOOLEAN IS
    BEGIN
        IF P_TELEFONO IS NULL OR TRIM(P_TELEFONO) IS NULL THEN RETURN TRUE; END IF;
        IF REGEXP_LIKE(TRIM(P_TELEFONO), '^[+]?[0-9\s-]{7,20}$') THEN RETURN TRUE; ELSE RETURN FALSE; END IF;
    END FN_VALIDAR_TELEFONO;

