        P_MENSAJE_ERROR       OUT VARCHAR2
    ) IS
        v_existe NUMBER := 0;
        CURSOR c_existe IS SELECT 1 FROM COMERCIANTE WHERE ID_COMERCIANTE = P_ID_COMERCIANTE;
