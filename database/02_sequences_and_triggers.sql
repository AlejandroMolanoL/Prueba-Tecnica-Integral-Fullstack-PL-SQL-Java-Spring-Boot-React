-- SCRIPT 02: SECUENCIAS Y DISPARADORES (TRIGGERS) DE ID Y AUDITORÍA
-- Motor: Oracle 11gR2 o superior
-- ====================================================================

-- 1. Secuencias para claves primarias
CREATE SEQUENCE SEQ_DEPARTAMENTO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_MUNICIPIO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_COMERCIANTE
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_ESTABLECIMIENTO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- ====================================================================
-- TRIGGERS DE IDENTIFICADOR Y AUDITORÍA
-- Cada trigger gestiona la secuencia (si ID es NULL) y actualiza
-- automáticamente los campos FECHA_ACTUALIZACION y USUARIO_ACTUALIZACION
-- tanto en INSERT como en UPDATE.
-- ====================================================================

-- Trigger para DEPARTAMENTO
CREATE OR REPLACE TRIGGER TRG_BIU_DEPARTAMENTO
BEFORE INSERT OR UPDATE ON DEPARTAMENTO
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        IF :NEW.ID_DEPARTAMENTO IS NULL THEN
            :NEW.ID_DEPARTAMENTO := SEQ_DEPARTAMENTO.NEXTVAL;
        END IF;
    END IF;
    
    :NEW.FECHA_ACTUALIZACION := SYSDATE;
    :NEW.USUARIO_ACTUALIZACION := NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER);
END TRG_BIU_DEPARTAMENTO;
/

