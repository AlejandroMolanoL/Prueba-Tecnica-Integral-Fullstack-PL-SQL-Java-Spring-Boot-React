-- 1. Tabla de Departamentos (Normalización de listas de valores)
CREATE TABLE DEPARTAMENTO (
    ID_DEPARTAMENTO      NUMBER(10)          NOT NULL,
    CODIGO_DANE          VARCHAR2(10)        NOT NULL,
    NOMBRE               VARCHAR2(100)       NOT NULL,
    FECHA_ACTUALIZACION  DATE                DEFAULT SYSDATE NOT NULL,
    USUARIO_ACTUALIZACION VARCHAR2(50)       DEFAULT USER NOT NULL,
    CONSTRAINT PK_DEPARTAMENTO PRIMARY KEY (ID_DEPARTAMENTO),
    CONSTRAINT UQ_DEPARTAMENTO_CODIGO UNIQUE (CODIGO_DANE)
);

-- 2. Tabla de Municipios (Normalización de listas de valores)
CREATE TABLE MUNICIPIO (
    ID_MUNICIPIO         NUMBER(10)          NOT NULL,
    ID_DEPARTAMENTO      NUMBER(10)          NOT NULL,
    CODIGO_DANE          VARCHAR2(10)        NOT NULL,
    NOMBRE               VARCHAR2(100)       NOT NULL,
    FECHA_ACTUALIZACION  DATE                DEFAULT SYSDATE NOT NULL,
    USUARIO_ACTUALIZACION VARCHAR2(50)       DEFAULT USER NOT NULL,
    CONSTRAINT PK_MUNICIPIO PRIMARY KEY (ID_MUNICIPIO),
    CONSTRAINT FK_MUNICIPIO_DEPTO FOREIGN KEY (ID_DEPARTAMENTO)
        REFERENCES DEPARTAMENTO (ID_DEPARTAMENTO),
    CONSTRAINT UQ_MUNICIPIO_CODIGO UNIQUE (CODIGO_DANE)
);

-- 3. Tabla Comerciante
CREATE TABLE COMERCIANTE (
    ID_COMERCIANTE        NUMBER(10)          NOT NULL,
    NOMBRE_RAZON_SOCIAL   VARCHAR2(200)       NOT NULL,
    DEPARTAMENTO          VARCHAR2(100)       NOT NULL,
    MUNICIPIO             VARCHAR2(100)       NOT NULL,
    TELEFONO              VARCHAR2(20),
    CORREO_ELECTRONICO    VARCHAR2(150),
    FECHA_REGISTRO        DATE                NOT NULL,
    ESTADO                VARCHAR2(20)        NOT NULL,
    FECHA_ACTUALIZACION   DATE                DEFAULT SYSDATE NOT NULL,
    USUARIO_ACTUALIZACION VARCHAR2(50)        DEFAULT USER NOT NULL,
    CONSTRAINT PK_COMERCIANTE PRIMARY KEY (ID_COMERCIANTE),
    CONSTRAINT CK_COMERCIANTE_ESTADO CHECK (
        ESTADO IN ('Registrado', 'Activo', 'Inactivo', 'Suspendido', 'Cancelado')
    )
);

-- 4. Tabla Establecimiento
CREATE TABLE ESTABLECIMIENTO (
    ID_ESTABLECIMIENTO    NUMBER(10)          NOT NULL,
    ID_COMERCIANTE        NUMBER(10)          NOT NULL,
    NOMBRE_ESTABLECIMIENTO VARCHAR2(200)      NOT NULL,
    INGRESOS              NUMBER(15, 2)       DEFAULT 0.00 NOT NULL,
    NUMERO_EMPLEADOS      NUMBER(6)           DEFAULT 0 NOT NULL,
    FECHA_ACTUALIZACION   DATE                DEFAULT SYSDATE NOT NULL,
    USUARIO_ACTUALIZACION VARCHAR2(50)        DEFAULT USER NOT NULL,
    CONSTRAINT PK_ESTABLECIMIENTO PRIMARY KEY (ID_ESTABLECIMIENTO),
    CONSTRAINT FK_ESTABLECIMIENTO_COM FOREIGN KEY (ID_COMERCIANTE)
        REFERENCES COMERCIANTE (ID_COMERCIANTE) ON DELETE CASCADE,
    CONSTRAINT CK_ESTABLECIMIENTO_INGRESOS CHECK (INGRESOS >= 0),
    CONSTRAINT CK_ESTABLECIMIENTO_EMPLEADOS CHECK (NUMERO_EMPLEADOS >= 0)
);

-- ====================================================================
-- DEFINICIÓN DE ÍNDICES NECESARIOS (RETO 01 / Reglas)
-- Optimizan búsquedas por filtros, claves foráneas y ordenamiento
-- ====================================================================

-- Índices sobre COMERCIANTE
CREATE INDEX IDX_COM_NOMBRE_RS ON COMERCIANTE(UPPER(NOMBRE_RAZON_SOCIAL));
CREATE INDEX IDX_COM_MUNICIPIO ON COMERCIANTE(UPPER(MUNICIPIO));
CREATE INDEX IDX_COM_FECHA_REG ON COMERCIANTE(FECHA_REGISTRO);
CREATE INDEX IDX_COM_ESTADO ON COMERCIANTE(ESTADO);
CREATE INDEX IDX_COM_CORREO ON COMERCIANTE(CORREO_ELECTRONICO);

-- Índices sobre ESTABLECIMIENTO
CREATE INDEX IDX_EST_COMERCIANTE ON ESTABLECIMIENTO(ID_COMERCIANTE);
CREATE INDEX IDX_EST_NOMBRE ON ESTABLECIMIENTO(UPPER(NOMBRE_ESTABLECIMIENTO));

-- Índices sobre DEPARTAMENTO y MUNICIPIO
CREATE INDEX IDX_DEPTO_NOMBRE ON DEPARTAMENTO(UPPER(NOMBRE));
CREATE INDEX IDX_MUNI_DEPTO ON MUNICIPIO(ID_DEPARTAMENTO);
CREATE INDEX IDX_MUNI_NOMBRE ON MUNICIPIO(UPPER(NOMBRE));

COMMIT;
